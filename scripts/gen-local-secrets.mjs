/**
 * Generate .env.local for the local production-like stack (docker-compose.prod.yml).
 *
 * These are development-only credentials for containers on this machine. Real
 * vendor keys (EcoCash, Paynow, Meta, ZIMRA, escrow) are never generated here —
 * they arrive from the founder and are added by name per Pack section 6.
 *
 *   node scripts/gen-local-secrets.mjs [--force]
 *
 * Existing values are preserved unless --force is passed, so re-running is safe
 * and will not invalidate the tokens already trusted by a running stack.
 */
import { createHmac, randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = join(repoRoot, ".env.local");
const force = process.argv.includes("--force");

function base64url(input) {
  return Buffer.from(input)
    .toString("base64")
    .replace(/\+/g, "-")
    .replace(/\//g, "_")
    .replace(/=+$/, "");
}

/** Supabase-shaped HS256 JWT so GoTrue and PostgREST accept the same secret. */
function signSupabaseJwt(role, secret) {
  const issuedAt = Math.floor(Date.now() / 1000);
  const header = base64url(JSON.stringify({ alg: "HS256", typ: "JWT" }));
  const payload = base64url(
    JSON.stringify({
      role,
      iss: "supabase",
      iat: issuedAt,
      exp: issuedAt + 60 * 60 * 24 * 365 * 5,
    }),
  );
  const signature = createHmac("sha256", secret)
    .update(`${header}.${payload}`)
    .digest("base64")
    .replace(/\+/g, "-")
    .replace(/\//g, "_")
    .replace(/=+$/, "");
  return `${header}.${payload}.${signature}`;
}

function parseEnvFile(path) {
  if (!existsSync(path)) return {};
  const out = {};
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const match = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (match) out[match[1]] = match[2];
  }
  return out;
}

const existing = force ? {} : parseEnvFile(envPath);
const secret = (bytes) => randomBytes(bytes).toString("hex");

const jwtSecret = existing.SUPABASE_JWT_SECRET || secret(32);

const values = {
  DIAL_INTEGRATION_MODE: existing.DIAL_INTEGRATION_MODE || "sandbox",
  POSTGRES_PASSWORD: existing.POSTGRES_PASSWORD || secret(16),
  AUTHENTICATOR_PASSWORD: existing.AUTHENTICATOR_PASSWORD || secret(16),
  AUTH_ADMIN_PASSWORD: existing.AUTH_ADMIN_PASSWORD || secret(16),
  TEMPORAL_DB_PASSWORD: existing.TEMPORAL_DB_PASSWORD || secret(16),
  SUPABASE_JWT_SECRET: jwtSecret,
  SUPABASE_ANON_KEY:
    existing.SUPABASE_ANON_KEY || signSupabaseJwt("anon", jwtSecret),
  SUPABASE_SERVICE_ROLE_KEY:
    existing.SUPABASE_SERVICE_ROLE_KEY ||
    signSupabaseJwt("service_role", jwtSecret),
  MEILI_MASTER_KEY: existing.MEILI_MASTER_KEY || secret(24),
  INTERNAL_API_SECRET: existing.INTERNAL_API_SECRET || secret(24),
  TEMPORAL_NAMESPACE: existing.TEMPORAL_NAMESPACE || "dial",
  DIAL_GATEWAY_BASE_URL:
    existing.DIAL_GATEWAY_BASE_URL || "http://localhost:3000",
  SUPABASE_EXTERNAL_URL:
    existing.SUPABASE_EXTERNAL_URL || "http://localhost:8000",
};

// Anything the operator already added by hand (vendor keys, map URLs) survives.
for (const [key, value] of Object.entries(existing)) {
  if (!(key in values)) values[key] = value;
}

const header = [
  "# DIAL local stack credentials — generated by scripts/gen-local-secrets.mjs.",
  "# Gitignored. Development only: never reuse these values on a shared host.",
  "# Vendor keys (Pack section 6) are added here by name when the founder supplies them.",
  "",
].join("\n");

const body = Object.entries(values)
  .map(([key, value]) => `${key}=${value}`)
  .join("\n");

writeFileSync(envPath, `${header}${body}\n`, "utf8");

const regenerated = Object.keys(values).filter((k) => !(k in existing));
console.log(`.env.local written (${Object.keys(values).length} keys)`);
console.log(
  regenerated.length
    ? `generated: ${regenerated.join(", ")}`
    : "no new values — existing credentials preserved",
);
